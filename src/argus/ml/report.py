import numpy as np

from .features import Dataset

SCHEME_NOTE = {
    "lopo": "leave-one-paper-out (headline)",
    "group5": "5-fold by paper, repeated",
    "random5": "5-fold by row, repeated (leaks papers; shown only for contrast)",
}


def predictions_table(ds: Dataset, res: dict[str, Any], best: str) -> list[dict[str, Any]]:
    """Per-row leave-one-paper-out predictions of every model, plus the best
    model's 90% group-conformal interval (same construction as group_conformal)."""
    preds = res["lopo_predictions"]
    resid = np.abs(preds[best] - ds.y)
    out = []
    for i, r in enumerate(ds.rows):
        others = resid[ds.groups != ds.groups[i]]
        n = len(others)
        q90 = float(np.quantile(others, min(1.0, 0.9 * (n + 1) / n), method="higher"))
        km = float(r["k_matrix_effective"])
        row = {"row_id": r["row_id"], "paper_id": r["paper_id"], "filler": r["filler_base"],
               "phi_vol_pct": r["phi_vol_pct"], "method_class": r["method_class"],
               "k_measured": float(r["k_composite_W_mK"])}
        for m, p in preds.items():
            row[f"k_pred_{m}"] = round(km * 10 ** float(p[i]), 4)
        row[f"k_{best}_lo90"] = round(km * 10 ** (float(preds[best][i]) - q90), 4)
        row[f"k_{best}_hi90"] = round(km * 10 ** (float(preds[best][i]) + q90), 4)
        out.append(row)
    return out


def parity_plot(ds: Dataset, res: dict[str, Any], models: list[str], path: Path) -> Path | None:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:  # matplotlib is optional
        return None
    km = np.array([float(r["k_matrix_effective"]) for r in ds.rows])
    k = km * 10 ** ds.y
    fig, axes = plt.subplots(1, len(models), figsize=(4.6 * len(models), 4.4), sharex=True, sharey=True)
    axes = np.atleast_1d(axes)
    lo, hi = 0.1, 60
    for ax, m in zip(axes, models):
        kp = km * 10 ** res["lopo_predictions"][m]
        met = res["models"][m]["lopo"]
        ax.fill_between([lo, hi], [lo / 2, hi / 2], [lo * 2, hi * 2], color="#d9d9d9", alpha=0.6, lw=0,
                        label="within factor 2")
        ax.plot([lo, hi], [lo, hi], color="#555555", lw=1)
        ax.scatter(k, kp, s=14, alpha=0.75, color="#1f6f8b", edgecolor="none")
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xlim(lo, hi)
        ax.set_ylim(lo, hi)
        ax.set_title(f"{m}: MAE ×{met['mae_factor']:.2f}, R² {met['r2']:.2f}", fontsize=10)
        ax.set_xlabel("measured k (W/m·K)")
    axes[0].set_ylabel("predicted k, paper held out (W/m·K)")
    axes[0].legend(loc="upper left", fontsize=8, frameon=False)
    fig.suptitle(f"Leave-one-paper-out predictions ({len(ds.y)} rows, {ds.n_papers} papers)", fontsize=11)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def render_markdown(res: dict[str, Any], abl: dict[str, Any] | None, figure: str | None) -> str:
    d = res["data"]
    best, base = res["best_model"], res["best_baseline"]
    acc = res.get("acceptance", {})
    M = res["models"]
    L: list[str] = ["# ML benchmark: predicting k for an unseen paper", "",
                    "_Generated by `argus ml benchmark`. Every number below comes from models that never saw the "
                    "test paper (except the row-level `random5` column, shown to expose leakage)._", ""]
    L += ["## Summary", ""]
    if best and base:
        b, m = M[base]["lopo"], M[best]["lopo"]
        L.append(f"- **{best} predicts k within a typical factor of {m['mae_factor']:.2f}** for a paper it has "
                 f"never seen (leave-one-paper-out MAE {m['mae_log10']:.3f} in log10; R² {m['r2']:.2f}; "
                 f"{100 * m['within_factor_2']:.0f}% of rows within a factor of 2).")
        verdict = "passes" if acc.get("passed") else "fails"
        phys = (f"; the physics-only baseline reaches ×{M['physics']['lopo']['mae_factor']:.2f}"
                if "physics" in M and base != "physics" else "")
        L.append(f"- **Acceptance {verdict}:** the best baseline ({base}) reaches ×{b['mae_factor']:.2f} "
                 f"(MAE {b['mae_log10']:.3f}){phys}.")
    if best == "ensemble":
        singles = [n for n in res["ranking_lopo_mae"] if n not in ("ensemble",) and not M[n]["baseline"]]
        if singles:
            s1 = singles[0]
            gap = M[s1]["lopo"]["mae_log10"] - M[best]["lopo"]["mae_log10"]
            L.append(f"- **The ensemble's members were chosen by comparing combinations on these same folds**, so its "
                     f"edge over the best single model ({s1}, MAE {gap:.3f} lower) is not evidence on its own. Its "
                     "out-of-sample confirmation is the test on other groups' data (reports/external_validation.md).")
    gaps = {n: e["leakage_gap_mae"] for n, e in M.items()}
    worst = max(gaps, key=gaps.get)
    L.append(f"- **Row-level random splits overstate accuracy.** For {worst}, random 5-fold MAE is "
             f"{M[worst]['random5']['mae_log10']:.3f} vs {M[worst]['group5']['mae_log10']:.3f} when papers are "
             "kept together. Published R² of 0.95–0.99 from random splits are not comparable.")
    c90 = M[best]["conformal_90"] if best else None
    if c90:
        L.append(f"- **Honest uncertainty is large.** 90% paper-grouped intervals cover "
                 f"{100 * c90['row_coverage']:.0f}% of rows but span ×/÷{c90['interval_factor_median']:.1f} around "
                 "the prediction: composition alone does not pin down k, because processing and measurement "
                 "differences between papers dominate (see reports/method_bias.md).")
    L.append("")

    L += ["## 1. Data", "",
          f"{d['rows']} single-filler rows from {d['papers']} papers with a known loading; target "
          f"`{d['target']}` (SD {d['target_sd']}). {d['features']} features in groups: {', '.join(d['feature_groups'])}. "
          "Hybrid-filler rows are excluded (no volume fraction).", ""]
    L += ["## 2. Results by validation scheme", "",
          "MAE in log10 units (×factor in brackets). Lower is better.", "",
          "| Model | Leave-one-paper-out | R² (LOPO) | Within ×2 | 5-fold by paper | 5-fold by row (leaky) | Time split (train ≤2021) |",
          "|---|---|---|---|---|---|---|"]
    for n in res["ranking_lopo_mae"]:
        e = M[n]
        tag = " (baseline)" if e["baseline"] else ""
        t = e["time_split"]
        tcell = f"{t['mae_log10']:.3f}" if t else "n/a"
        L.append(f"| **{n}**{tag} | {e['lopo']['mae_log10']:.3f} (×{e['lopo']['mae_factor']:.2f}) | {e['lopo']['r2']:.2f} | "
                 f"{100 * e['lopo']['within_factor_2']:.0f}% | {e['group5']['mae_log10']:.3f} ± {e['group5']['mae_log10_sd']:.3f} | "
                 f"{e['random5']['mae_log10']:.3f} | {tcell} |")
    L += ["", "Models:"] + [f"- `{n}`: {M[n]['description']}" for n in M] + [""]

    fams = list(next(iter(M.values()))["filler_out"])
    if fams:
        L += ["## 3. Extrapolation to an unseen filler family", "",
              "Train without one family, test on it (MAE log10).", "",
              "| Model | " + " | ".join(f"{f} held out ({d['filler_out'][f]} rows)" for f in fams) + " |",
              "|---|" + "---|" * len(fams)]
        for n in res["ranking_lopo_mae"]:
            L.append(f"| {n} | " + " | ".join(f"{M[n]['filler_out'][f]['mae_log10']:.3f}" for f in fams) + " |")
        L.append("")

    L += ["## 4. Prediction intervals (group-conformal)", "",
          "For each held-out paper, the half-width is the quantile of the other papers' absolute "
          "leave-one-paper-out errors.", "",
          "| Model | 68% coverage | 68% width | 90% coverage | 90% width |", "|---|---|---|---|---|"]
    for n in res["ranking_lopo_mae"]:
        a, b = M[n]["conformal_68"], M[n]["conformal_90"]
        L.append(f"| {n} | {100 * a['row_coverage']:.0f}% | ×/÷{a['interval_factor_median']:.2f} | "
                 f"{100 * b['row_coverage']:.0f}% | ×/÷{b['interval_factor_median']:.2f} |")
    L.append("")

    if abl:
        clear = [g["group"] for g in abl["groups"] if g.get("clear")]
        L += [f"## 5. Which information helps? (ablation, {abl['model']}, {abl['scheme']})", "",
              f"MAE with all features: {abl['mae_all_features']:.3f}. Δ = MAE without the group minus MAE with it, "
              f"averaged over {abl['repeats']} paper-grouped 5-fold repeats that use the same splits (paired). "
              "Positive Δ = the group helps predict unseen papers.", "",
              "| Feature group removed | MAE | Δ (mean ± SD over repeats) | Clearly helps (Δ > 2 SD) |",
              "|---|---|---|---|"]
        for g in abl["groups"]:
            sd = f" ± {g['delta_sd']:.3f}" if g.get("delta_sd") is not None else ""
            L.append(f"| {g['group']} | {g['mae_without']:.3f} | {g['delta_mae']:+.3f}{sd} | "
                     f"{'yes' if g.get('clear') else ''} |")
        L += ["", ("Clearly helpful: " + ", ".join(clear) + ". Others are not distinguishable from zero with this "
                   "data." if clear else "No group clearly helps on its own with this data."),
              "Rows with '+' remove two groups that overlap (the physics feature is computed from loading; the "
              "method implies a default direction), so a group can look unimportant alone while the pair matters.", ""]

    if figure:
        L += ["## 6. Parity plot", "", f"![parity]({figure})", ""]
    L += ["## Caveats", "",
          f"- {d['papers']} papers is small: differences between learned models of a few 0.01 log10 are within "
          "noise (see the ± column).",
          "- Loading is partly converted from wt% and k_m is partly a family default (`*_basis` columns); "
          "both add error that no model can remove."]
    ts = d.get("time_split")
    if ts:
        tr, te = ts["train"], ts["test"]
        diffs = [f"{label} {100 * te[key]:.0f}% vs {100 * tr[key]:.0f}% of rows"
                 for key, label in (("share_BNNS", "BNNS"), ("share_aligned", "aligned fillers"))
                 if round(100 * te[key]) != round(100 * tr[key])]
        dm = te["median_target_log10"] - tr["median_target_log10"]
        if abs(dm) >= 0.005:
            diffs.append(f"a {'lower' if dm < 0 else 'higher'} median enhancement "
                         f"({te['median_target_log10']:.2f} vs {tr['median_target_log10']:.2f} log10)")
        shift = (f" Papers from 2022 on differ from older ones: {', '.join(diffs[:-1])}"
                 f"{' and ' if len(diffs) > 1 else ''}{diffs[-1]}. A model trained on older papers meets a "
                 "shifted population.") if diffs else ""
        L.append(f"- The time split is harder than leave-one-paper-out.{shift}")
        timed = {n: e["time_split"]["mae_log10"] for n, e in M.items() if e.get("time_split")}
        if timed:
            bt = min(timed, key=timed.get)
            L[-1] += f" On this split the best model is {bt} (MAE {timed[bt]:.3f})."
    L += ["- Intervals are calibrated on average over papers, not for every paper.", ""]
    return "\n".join(L)
