"""Release metadata: CITATION.cff, author names and a formatted citation.

Everything derives from data/dataset.yaml so the version, date, authors and
licence cannot drift between CITATION.cff, datapackage.json, the course report
and the explorer.
"""
from __future__ import annotations

from typing import Any

from .io import load_yaml
from .paths import Layout

LICENSE_INFO = {
    "CC-BY-4.0": ("Creative Commons Attribution 4.0 International", "https://creativecommons.org/licenses/by/4.0/"),
    "MIT": ("MIT License", "https://opensource.org/license/mit"),
}


def dataset_meta(lay: Layout) -> dict[str, Any]:
    path = lay.data / "dataset.yaml"
    return (load_yaml(path) or {}) if path.exists() else {}


def author_names(meta: dict[str, Any]) -> list[str]:
    return [" ".join(x for x in (a.get("given-names", ""), a.get("family-names", "")) if x)
            for a in meta.get("authors", [])]


def _initials(given: str) -> str:
    return " ".join(p[0] + "." for p in given.split() if p)


def citation_text(meta: dict[str, Any]) -> str:
    """APA-style: Kumar, A., & Reddy, R. K. S. (2026). Title (Version 1.1.0) [Data set]. URL"""
    authors = meta.get("authors", [])
    parts = [f"{a.get('family-names', '')}, {_initials(a.get('given-names', ''))}".strip(", ") for a in authors]
    if len(parts) > 1:
        names = ", ".join(parts[:-1]) + ", & " + parts[-1]
    else:
        names = parts[0] if parts else ""
    year = str(meta.get("released", ""))[:4]
    where = f"https://doi.org/{meta['doi']}" if meta.get("doi") else meta.get("homepage", "")
    publisher = f"{meta['publisher']}. " if meta.get("doi") and meta.get("publisher") else ""
    return (f"{names} ({year}). ARGUS: {meta.get('title', '')} (Version {meta.get('version', '')}) [Data set]. "
            f"{publisher}{where}")


def fulltext_licences(lay: Layout) -> dict[str, tuple[str, str | None]]:
    """Licence stated in each stored full text: stem -> (kind, version).

    kind is 'NC', 'BY' or 'none'. Joins words and URLs hyphenated across line
    breaks first, and matches licence wording as well as URLs, because many
    extracted texts state the licence in words or split the URL.
    """
    import re

    out: dict[str, tuple[str, str | None]] = {}
    for p in sorted((lay.legacy / "fulltext").glob("*.txt")):
        t = re.sub(r"-\s*\n\s*", "", p.read_text(encoding="utf-8", errors="replace")).lower()
        if re.search(r"licenses/by-nc|attribution[- ]non-?commercial|cc by-nc", t):
            kind = "NC"
        elif re.search(r"licenses/by/|creative commons attribution|\bcc by\b", t):
            kind = "BY"
        else:
            out[p.stem] = ("none", None)
            continue
        m = re.search(r"licenses/by(?:-nc)?/(\d\.\d)", t) or re.search(r"attribution[^.]{0,40}?(\d\.\d)", t)
        out[p.stem] = (kind, m.group(1) if m else None)
    return out


def _q(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def citation_cff(meta: dict[str, Any]) -> str:
    """CITATION.cff (Citation File Format 1.2.0), written deterministically.

    Only the DATA licence goes under `license`: CFF reads a list of licences as
    alternatives (OR), so listing the code's MIT licence there would offer the
    dataset under MIT. The code licence is stated in LICENSE and the message.
    """
    msg = "If you use this dataset or the argus toolkit, please cite it as below."
    if meta.get("license") and meta.get("code_license"):
        msg += (f" The data are licensed {meta['license']}; the code is licensed {meta['code_license']} "
                "(LICENSE in the repository).")
    lines = [
        "# Generated by `argus build` from data/dataset.yaml. Edit that file, not this one.",
        "cff-version: 1.2.0",
        f"message: {_q(msg)}",
        "type: dataset",
        f"title: {_q('ARGUS: ' + meta.get('title', ''))}",
    ]
    if meta.get("version"):
        lines.append(f"version: {_q(meta['version'])}")
    if meta.get("doi"):
        lines.append(f"doi: {_q(meta['doi'])}")
    if meta.get("released"):
        lines.append(f"date-released: {_q(meta['released'])}")
    authors = [a for a in meta.get("authors", []) if a.get("family-names") or a.get("given-names")]
    if not authors:
        raise ValueError("data/dataset.yaml needs at least one author with family-names or given-names")
    lines.append("authors:")
    for a in authors:
        keys = [k for k in ("family-names", "given-names") if a.get(k)]
        for j, k in enumerate(keys):
            lines.append(f"  {'- ' if j == 0 else '  '}{k}: {_q(a[k])}")
    if meta.get("license"):
        lines.append(f"license: {meta['license']}")
    if meta.get("homepage"):
        lines.append(f"repository-code: {_q(meta['homepage'])}")
        lines.append(f"url: {_q(meta['homepage'])}")
    if meta.get("description"):
        lines.append(f"abstract: {_q(' '.join(str(meta['description']).split()))}")
    if meta.get("keywords"):
        lines.append("keywords:")
        lines += [f"  - {_q(k)}" for k in meta["keywords"]]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- Zenodo

ZENODO_LICENSE = {"CC-BY-4.0": "cc-by-4.0", "MIT": "mit"}


def zenodo_metadata(meta: dict[str, Any]) -> dict[str, Any]:
    """Deposition metadata in Zenodo's format (.zenodo.json / the upload form).

    Generated from data/dataset.yaml like CITATION.cff, so the two cannot drift.
    """
    creators = [{"name": ", ".join(x for x in (a.get("family-names", ""), a.get("given-names", "")) if x)}
                for a in meta.get("authors", []) if a.get("family-names") or a.get("given-names")]
    if not creators:
        raise ValueError("data/dataset.yaml needs at least one author")
    desc = " ".join(str(meta.get("description", "")).split())
    notes = []
    if meta.get("code_license"):
        notes.append(f"Data licensed {meta.get('license', '')}; the argus toolkit in the repository is licensed "
                     f"{meta['code_license']}.")
    notes.append("Third-party papers are not included; every row cites the DOI of its source.")
    out: dict[str, Any] = {
        "upload_type": "dataset",
        "title": "ARGUS: " + meta.get("title", ""),
        "creators": creators,
        "description": desc,
        "version": meta.get("version", ""),
        "publication_date": str(meta.get("released", "")),
        "license": ZENODO_LICENSE.get(meta.get("license", ""), str(meta.get("license", "")).lower()),
        "access_right": "open",
        "keywords": list(meta.get("keywords", [])),
        "notes": " ".join(notes),
    }
    if meta.get("homepage"):
        out["related_identifiers"] = [{"identifier": meta["homepage"], "relation": "isSupplementedBy",
                                       "resource_type": "software", "scheme": "url"}]
    if meta.get("doi"):
        out["doi"] = meta["doi"]
    return out


def zenodo_json(meta: dict[str, Any]) -> str:
    import json

    return json.dumps(zenodo_metadata(meta), indent=2, ensure_ascii=False) + "\n"


# Files that make up the published dataset (relative to the repository root).
# The repository's LICENSE-DATA.md is not among them: it describes the whole repository (code,
# documents, third-party files), so the archive gets its own LICENSE.txt (bundle_licence).
BUNDLE_FILES = ("thermal_conductivity_dataset.csv", "paper_inventory.csv", "extraction_log.csv",
                "uncertain_measurements.csv", "unusable_sources.csv", "datapackage.json", "CITATION.cff",
                "data/dataset.yaml", "data/CHANGELOG.md", "data/curation_log.yaml",
                "data/exclusions.yaml", "data/tombstones.yaml", "data/processed/measurements_enriched.csv")
BUNDLE_DIRS = ("data/records",)
_ZIP_TIME = (2026, 1, 1, 0, 0, 0)
# Line endings in the bundle, independent of the checkout (core.autocrlf, files rewritten by the
# toolkit): CSVs CRLF as `.gitattributes` pins them, every other text file LF. These are the
# bytes of a checkout with core.autocrlf=false.
_TEXT_SUFFIXES = (".csv", ".json", ".jsonl", ".yaml", ".yml", ".md", ".cff", ".txt")
_CRLF_SUFFIXES = (".csv",)


def canonical_bytes(member: str, raw: bytes) -> bytes:
    if not member.lower().endswith(_TEXT_SUFFIXES):
        return raw
    lf = raw.replace(b"\r\n", b"\n")
    return lf.replace(b"\n", b"\r\n") if member.lower().endswith(_CRLF_SUFFIXES) else lf


def bundle_members(lay: Layout) -> list[str]:
    members = [f for f in BUNDLE_FILES if (lay.root / f).exists()]
    for d in BUNDLE_DIRS:
        members += sorted(p.relative_to(lay.root).as_posix() for p in (lay.root / d).glob("*.yaml"))
    return sorted(members)


def bundle_licence(meta: dict[str, Any]) -> str:
    """LICENSE.txt for the archive: what the licence covers inside the zip, and only that."""
    title, url = LICENSE_INFO.get(meta.get("license", ""), (meta.get("license", ""), ""))
    names = author_names(meta)
    holders = " and ".join([", ".join(names[:-1]), names[-1]]) if len(names) > 1 else "".join(names)
    code = meta.get("code_license", "")
    lines = [
        "Licence for this archive", "",
        f"ARGUS: {meta.get('title', '')}, version {meta.get('version', '')}",
        f"(c) {str(meta.get('released', ''))[:4]} {holders}", "",
        f"Every file in this archive is licensed under the {title} licence ({meta.get('license', '')}),",
        "except the quoted passages described below.",
    ]
    if url:
        lines += [f"  Summary:    {url}", f"  Legal code: {url}legalcode"]
    lines += [
        "",
        "Quoted passages. To make every value traceable, text fields of the tables and records (for",
        "example source_location, notes, and extraction-log fields such as tables_inspected and",
        "qc_findings) contain short verbatim quotations from the cited papers. Those passages remain",
        "the work of their authors under the source papers' own licences, whatever those are, and are",
        "not relicensed here. The measured values themselves are facts reported by those papers.",
        "When you reuse a value, cite its source paper (the DOI is in every row) as well as this",
        "dataset.",
        "",
        "Contents. The archive holds the dataset only: the published tables, the per-paper source",
        "records and the metadata. It contains no third-party papers, figures or external datasets,",
        "and no code." + (f" The argus toolkit that builds and checks the dataset is licensed {code}"
                          f" and lives in the repository: {meta.get('homepage', '')}" if code else ""),
        "",
        "No warranty. The dataset is provided as is. Values were transcribed or digitized from the",
        "cited sources and checked against them, but check a value against its source before using it",
        "in a publication, a design or a regulatory context.",
    ]
    return "\n".join(lines) + "\n"


def bundle_readme(meta: dict[str, Any], members: list[str]) -> str:
    lines = [f"ARGUS: {meta.get('title', '')}", f"Version {meta.get('version', '')} ({meta.get('released', '')})", "",
             "Authors: " + ", ".join(author_names(meta)), f"Licence: {meta.get('license', '')} (see LICENSE.txt)",
             f"Repository: {meta.get('homepage', '')}", "", "How to cite:", "  " + citation_text(meta), "",
             " ".join(str(meta.get("description", "")).split()), "",
             "Main table: thermal_conductivity_dataset.csv (one measured k per row; columns described in",
             "datapackage.json). data/processed/measurements_enriched.csv adds derived columns; converted",
             "or defaulted quantities (method, direction, vol%, wt%, k_matrix) carry a *_basis column.",
             "data/records/ holds the per-paper source records (the source of truth). Documentation, the",
             "code and the analyses live in the repository above.",
             "SHA256SUMS.txt lists the checksum of every file.", "",
             "Files:"] + [f"  {m}" for m in members]
    return "\n".join(lines) + "\n"


def build_bundle(lay: Layout, out_dir) -> tuple[Any, str]:
    """dist/ARGUS-dataset-v<version>.zip: the dataset files only (no third-party papers,
    no code). Returns (path, sha256).

    Reproducible: member bytes are normalised by canonical_bytes, so SHA256SUMS.txt is the same
    on every platform and checkout; with fixed timestamps and modes, the zip itself is too, given
    the same zlib build."""
    import hashlib
    import zipfile
    from pathlib import Path

    meta = dataset_meta(lay)
    members = bundle_members(lay)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    name = f"ARGUS-dataset-v{meta.get('version', '0')}"
    path = out_dir / f"{name}.zip"
    data = {m: canonical_bytes(m, (lay.root / m).read_bytes()) for m in members}
    data["LICENSE.txt"] = bundle_licence(meta).encode("utf-8")
    data["README.txt"] = bundle_readme(meta, sorted([*members, "LICENSE.txt"])).encode("utf-8")
    sums = "".join(f"{hashlib.sha256(b).hexdigest()}  {m}\n" for m, b in sorted(data.items()))
    data["SHA256SUMS.txt"] = sums.encode("utf-8")
    tmp = path.with_suffix(".zip.tmp")
    with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for m in sorted(data):
            info = zipfile.ZipInfo(f"{name}/{m}", date_time=_ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data[m])
    tmp.replace(path)
    return path, hashlib.sha256(path.read_bytes()).hexdigest()
